/**
 * Brand logos arrive from twelve different sources, in twelve different
 * formats, each with its own padding inside the file. Rendered at one CSS
 * height they read as twelve different sizes.
 *
 * This normalises them: rasterise, trim the transparent margin, flatten the
 * artwork to a single ink colour, and write the true aspect ratio into a
 * manifest so the component can size each logo by optical area rather than
 * by height.
 *
 *   node scripts/normalize-brand-logos.mjs
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const SOURCE = "assets/brand-logos";
const OUT = "public/brands";
const MANIFEST = "src/content/brand-logos.ts";

/** long edge of the written file, roughly 8x the largest slot on the page */
const LONG_EDGE = 1200;

fs.mkdirSync(OUT, { recursive: true });

const entries = [];

for (const file of fs.readdirSync(SOURCE).sort()) {
  const slug = path.parse(file).name;
  const input = path.join(SOURCE, file);

  // SVG needs a density high enough that the rasterised artwork clears
  // LONG_EDGE before the trim, otherwise the trim throws away resolution.
  const probe = await sharp(input).metadata();
  const density = file.endsWith(".svg")
    ? Math.min(2400, Math.ceil((72 * LONG_EDGE * 1.6) / Math.max(probe.width, probe.height)))
    : 72;

  const trimmed = await sharp(input, { density })
    .ensureAlpha()
    .trim({ threshold: 1 })
    .toBuffer({ resolveWithObject: true });

  const { width, height } = trimmed.info;
  const scale = LONG_EDGE / Math.max(width, height);

  // Every logo becomes one ink colour. The band inverts it to white, and a
  // two colour mark would otherwise invert into two greys.
  const mask = await sharp(trimmed.data)
    .resize({
      width: Math.round(width * scale),
      height: Math.round(height * scale),
      fit: "fill",
      kernel: "lanczos3",
    })
    .extractChannel("alpha")
    .toBuffer();

  await sharp({
    create: {
      width: Math.round(width * scale),
      height: Math.round(height * scale),
      channels: 3,
      background: "#000000",
    },
  })
    .joinChannel(mask)
    .png({ compressionLevel: 9 })
    .toFile(path.join(OUT, `${slug}.png`));

  entries.push({ slug, ratio: Number((width / height).toFixed(4)) });
  console.log(
    `${slug.padEnd(16)} ${width}x${height}  ratio ${(width / height).toFixed(2)}`,
  );
}

const body = `// Generated by scripts/normalize-brand-logos.mjs. Do not edit by hand.
//
// \`ratio\` is the trimmed artwork's width over its height, which is what lets
// the band size every logo to the same optical area.
export const brandLogos: Record<string, { ratio: number }> = {
${entries.map((e) => `  "${e.slug}": { ratio: ${e.ratio} },`).join("\n")}
};
`;

fs.writeFileSync(MANIFEST, body);
console.log(`\nwrote ${MANIFEST}`);
